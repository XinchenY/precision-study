/**
 * ============================================================================
 *  config.hpp — 全局参数配置
 * ============================================================================
 *
 *  CPU 和 GPU 共用的所有物理和数值参数。
 *  修改此处即可同步两个 backend, 无需分别修改 .cpp 和 .cu 文件。
 *
 *  HD 宏定义: 让同一个函数可同时在 CPU (host) 和 GPU (device) 上调用。
 *  编译 .cu 时 __CUDACC__ 自动定义, HD 展开为 __host__ __device__;
 *  编译 .cpp 时 HD 展开为空, 不影响普通 C++ 编译。
 *
 * ============================================================================
 */

#ifndef CONFIG_HPP
#define CONFIG_HPP

// ============================================================================
//  CPU/GPU 兼容: 让 g++ 忽略 CUDA 关键词
//  nvcc 编译 .cu 时自带 __host__/__device__, 不进这个 #ifndef
//  g++ 编译 .cpp 时不认识这两个词, 这里定义为空让它忽略
// ============================================================================
#ifndef __CUDACC__
  #define __host__
  #define __device__
#endif

// ============================================================================
//  精度开关
//  编译时加 -DUSE_FLOAT 即切换为 float, 不加则默认 double
//  例: g++ -DUSE_FLOAT -O3 src/riemann1d_cpu.cpp -o bin/riemann1d_fp32
// ============================================================================
#ifdef USE_FLOAT
typedef float Real;
#else
typedef double Real;
#endif

// ============================================================================
//  物理常数
// ============================================================================
#define GAMMA 1.4               // 理想气体比热比 γ = c_p / c_v

// ============================================================================
//  计算域范围
//  shock-bubble 问题: 激波从左向右传播, 气泡位于域中部
// ============================================================================
#define X_MIN 0.0               // x 左边界
#define X_MAX 0.225             // x 右边界 (22.5 cm)
#define Y_MIN 0.0               // y 下边界 (半域)
#define Y_MAX 0.089             // y 上边界 (8.9 cm)

// ============================================================================
//  网格参数
//  ghost = 2: MUSCL 重构需要 2 层鬼格子 (stencil 宽度 = 4)
// ============================================================================
#define NX    500               // x 方向内部格子数
#define NY    197               // y 方向内部格子数
#define GHOST 2                 // 鬼格子层数 (每侧)
#define TOTAL_X (NX + 2 * GHOST)  // x 方向总格子数 (含鬼格子) = 504
#define TOTAL_Y (NY + 2 * GHOST)  // y 方向总格子数 (含鬼格子) = 201
#define TOTAL_SIZE (TOTAL_X * TOTAL_Y)
#define DX ((Real)(X_MAX - X_MIN) / (Real)NX)  // x 方向网格间距
#define DY ((Real)(Y_MAX - Y_MIN) / (Real)NY)  // y 方向网格间距

// ============================================================================
//  时间参数
// ============================================================================
#define CFL_NUM  0.8            // CFL 数 (0 < CFL < 1, 越小越稳定)
#define T_END    0.0011741      // 终止时间 (对应 τ=19 无量纲时间)

// ============================================================================
//  激波-气泡问题物理参数 (Haas & Sturtevant 实验)
//
//  物理场景: Mach 1.22 的激波从左侧传入, 撞击静止的氦气泡
//  初始条件通过 Rankine-Hugoniot 跳跃关系式计算
// ============================================================================
#define RHO_AIR     1.29        // 空气密度 (kg/m³)
#define RHO_HELIUM  0.214       // 氦气密度 (kg/m³)
#define P_ATM       101325.0    // 大气压 (Pa)
#define MACH_NUM    1.22        // 入射激波马赫数
#define BUBBLE_R    0.025       // 气泡半径 (2.5 cm)
#define BUBBLE_X    0.035       // 气泡中心 x 坐标 (3.5 cm)
#define BUBBLE_Y    (0.089 / 2.0)  // 气泡中心 y 坐标 (半域中心)
#define SHOCK_X     0.005       // 初始激波位置 (0.5 cm)

#endif // CONFIG_HPP
